/** Fixed rate used to store euro prices in lei. */
export const EUR_TO_RON = 5;

export function priceInRon(l: Pick<SeedListing, "price" | "eur">) {
  if (l.eur !== undefined) {
    const ron = l.eur * EUR_TO_RON;
    // Round the way a person would write it: to 10 lei for rents, 100 lei above that.
    return ron < 20000 ? Math.round(ron / 10) * 10 : Math.round(ron / 100) * 100;
  }
  return l.price ?? 0;
}

